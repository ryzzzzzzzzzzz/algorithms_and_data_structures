/*
7. Дан номер дня – целое число от 1 до 31 и месяца — целое число в диапазоне 1–12 (1 — январь, 2 — февраль и т. д.). Вывести дату в виде текста (например, «пятое января»).
*/

import { integer, requireCondition } from '../../lib/input.js';
export const title = 'Дата прописью';
export const example = [5, 1];

const days = [
  '', 'первое', 'второе', 'третье', 'четвертое', 'пятое', 'шестое', 'седьмое',
  'восьмое', 'девятое', 'десятое', 'одиннадцатое', 'двенадцатое', 'тринадцатое',
  'четырнадцатое', 'пятнадцатое', 'шестнадцатое', 'семнадцатое', 'восемнадцатое',
  'девятнадцатое', 'двадцатое', 'двадцать первое', 'двадцать второе', 'двадцать третье',
  'двадцать четвертое', 'двадцать пятое', 'двадцать шестое', 'двадцать седьмое',
  'двадцать восьмое', 'двадцать девятое', 'тридцатое', 'тридцать первое',
];
const months = ['', 'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const monthLengths = [0, 31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

export default function solve(day, month) {
  integer(day, 'День', 1, 31);
  integer(month, 'Месяц', 1, 12);
  // Год не задан: 29 февраля считается допустимой датой.
  requireCondition(day <= monthLengths[month], 'Такой даты в выбранном месяце нет.');
  return `${days[day]} ${months[month]}`;
}
