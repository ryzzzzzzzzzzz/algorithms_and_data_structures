/*
10. В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов, обозначаемых названиями цвета: зеленый, красный, желтый, белый и черный. В каждом подцикле годы носят названия животных: крысы, коровы, тигра, зайца, дракона, змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи. По номеру года определить его название, если 1984 год — начало цикла: «год зеленой крысы».
*/

import { integer } from '../../lib/input.js';
export const title = 'Название года в учебном 60-летнем цикле';
export const example = [1984];

const animals = ['крысы', 'коровы', 'тигра', 'зайца', 'дракона', 'змеи',
  'лошади', 'овцы', 'обезьяны', 'курицы', 'собаки', 'свиньи'];
const feminine = ['зеленой', 'красной', 'желтой', 'белой', 'черной'];
const masculine = ['зеленого', 'красного', 'желтого', 'белого', 'черного'];

export default function solve(year) {
  integer(year, 'Год', 1);
  const offset = ((year - 1984) % 60 + 60) % 60;
  const animal = offset % 12;
  const color = Math.floor(offset / 12);
  const adjective = animal >= 2 && animal <= 4 ? masculine[color] : feminine[color];
  return `год ${adjective} ${animals[animal]}`;
}
